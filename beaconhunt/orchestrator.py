"""Headless orchestration behind the launcher GUI.

Everything the launcher does that is *not* Tkinter lives here so it can be
tested and reused without a display: resolving paths (source tree or a frozen
PyInstaller bundle), generating a scenario, driving docker compose, waiting for
sshd, opening a terminal already SSH'd in, and starting the web UI in-process.
"""

from __future__ import annotations

import os
import platform
import socket
import subprocess
import sys
import threading
import time
import webbrowser
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from . import safety

OnLine = Callable[[str], None]

SSH_HOST = "127.0.0.1"
SSH_PORT = 2222
DEFENDER_USER = "defender"


# --------------------------------------------------------------------------- #
# paths — work both from the source tree and a PyInstaller onefile bundle
# --------------------------------------------------------------------------- #

def _base_dir() -> Path:
    if getattr(sys, "frozen", False):            # PyInstaller onefile
        return Path(getattr(sys, "_MEIPASS"))
    return Path(__file__).resolve().parent.parent


def base_dir() -> Path:
    return _base_dir()


def state_dir() -> Path:
    if getattr(sys, "frozen", False):
        # _MEIPASS is wiped on exit; keep state somewhere stable per-user.
        d = Path.home() / ".beaconhunt" / "state"
    else:
        d = _base_dir() / "state"
    d.mkdir(parents=True, exist_ok=True)
    return d


def compose_file() -> Path:
    return _base_dir() / "docker-compose.yml"


def catalog_dir() -> Path:
    return _base_dir() / "catalog"


# --------------------------------------------------------------------------- #
# config
# --------------------------------------------------------------------------- #

@dataclass
class LaunchConfig:
    seed: int | None = None
    count: int = 5
    services: list[str] = field(default_factory=lambda: ["ssh"])
    difficulty: str | None = None
    web_port: int = 8800
    web_user: str = "hunter"
    web_password: str = ""          # blank -> generated by the web server
    open_terminal: bool = True
    open_browser: bool = True


# --------------------------------------------------------------------------- #
# steps
# --------------------------------------------------------------------------- #

def generate(cfg: LaunchConfig, log: OnLine):
    from .catalog import load_catalog
    from .scenario import generate_scenario
    from .session import load_round, save_round

    cat = load_catalog(catalog_dir())
    scenario = generate_scenario(
        cat,
        seed=cfg.seed,
        count=cfg.count,
        services=cfg.services or None,
        difficulties=[cfg.difficulty] if cfg.difficulty else None,
    )
    scenario.save(state_dir())
    save_round(load_round(scenario.seed, state_dir()), state_dir())
    log(f"Scenario seed={scenario.seed}: {len(scenario.findings)} finding(s), "
        f"{scenario.total_points} pts.")
    return scenario


def _compose(*args: str) -> list[str]:
    return ["docker", "compose", "-p", safety.COMPOSE_PROJECT,
            "-f", str(compose_file()), *args]


def _stream(cmd: list[str], log: OnLine) -> int:
    log("$ " + " ".join(cmd))
    try:
        proc = subprocess.Popen(
            cmd, cwd=str(_base_dir()),
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, bufsize=1,
        )
    except FileNotFoundError:
        log("ERROR: docker not found. Install Docker Desktop and try again.")
        return 127
    assert proc.stdout is not None
    for line in proc.stdout:
        log(line.rstrip())
    return proc.wait()


def deploy(scenario, log: OnLine) -> int:
    safety.require_in_scope("localhost")
    log("Building and starting the range (first run can take a few minutes)…")
    rc = _stream(_compose("up", "-d", "--build"), log)
    if rc != 0:
        return rc

    by_service: dict[str, list[str]] = {}
    for f in scenario.findings:
        by_service.setdefault(f.service, []).append(f.artifact_id)

    for service, ids in by_service.items():
        if service == "host":
            continue
        log(f"Planting {len(ids)} finding(s) in '{service}'…")
        rc = _stream(_compose("exec", "-T", service,
                              "/opt/beaconhunt/plant/plant-dispatch.sh", *ids), log)
        if rc != 0:
            log(f"WARNING: planting in {service} returned {rc}")
    return 0


def wait_for_ssh(log: OnLine, timeout: float = 60.0) -> bool:
    log(f"Waiting for sshd on {SSH_HOST}:{SSH_PORT}…")
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with socket.create_connection((SSH_HOST, SSH_PORT), timeout=2):
                log("sshd is up.")
                return True
        except OSError:
            time.sleep(1.0)
    log("Timed out waiting for sshd (the range may still be building).")
    return False


def open_ssh_terminal(log: OnLine, user: str = DEFENDER_USER) -> None:
    ssh = f"ssh {user}@{SSH_HOST} -p {SSH_PORT}"
    system = platform.system()
    log(f"Opening a terminal: {ssh}")
    try:
        if system == "Windows":
            hint = f"echo BeaconHunt {user} login ^(password: defender^) & {ssh}"
            subprocess.Popen(f'start "BeaconHunt SSH" cmd /k "{hint}"', shell=True)
        elif system == "Darwin":
            script = (f'tell application "Terminal" to activate\n'
                      f'tell application "Terminal" to do script "{ssh}"')
            subprocess.Popen(["osascript", "-e", script])
        else:
            import shutil
            for term in (["x-terminal-emulator", "-e"], ["gnome-terminal", "--"],
                         ["konsole", "-e"], ["xterm", "-e"]):
                if shutil.which(term[0]):
                    subprocess.Popen(term + ["bash", "-c", f"{ssh}; exec bash"])
                    break
            else:
                log(f"No terminal emulator found. Run manually: {ssh}")
    except Exception as exc:  # never let this crash the launch
        log(f"Could not open a terminal ({exc}). Run manually: {ssh}")


_web_started = False


def start_web(cfg: LaunchConfig, log: OnLine) -> str:
    """Start the submission web UI in a daemon thread (once per process)."""
    global _web_started
    from . import webui

    url = f"http://127.0.0.1:{cfg.web_port}"
    if _web_started:
        log(f"Web UI already running at {url}.")
        return url

    password = cfg.web_password or os.environ.get("BEACONHUNT_WEB_PASSWORD") or ""
    generated = ""
    if not password:
        import secrets
        password = secrets.token_urlsafe(9)
        generated = password

    def run():
        try:
            webui.serve(catalog_dir(), state_dir(), port=cfg.web_port,
                        user=cfg.web_user, password=password, auth=True)
        except Exception as exc:
            log(f"Web UI error: {exc}")

    threading.Thread(target=run, daemon=True).start()
    _web_started = True
    log(f"Web UI on {url}  (user: {cfg.web_user}"
        + (f" · password: {generated}" if generated else " · password: as set") + ")")
    return url


def open_browser(url: str, log: OnLine) -> None:
    try:
        webbrowser.open(url)
    except Exception as exc:
        log(f"Could not open browser ({exc}); go to {url}")


def teardown(log: OnLine) -> int:
    safety.require_in_scope("localhost")
    return _stream(_compose("down", "-v"), log)


def run_launch(cfg: LaunchConfig, log: OnLine) -> None:
    """Full sequence: generate → deploy → wait → terminal → web → browser."""
    try:
        scenario = generate(cfg, log)
        rc = deploy(scenario, log)
        if rc not in (0,):
            log(f"Deploy failed (rc={rc}). Is Docker Desktop running?")
            return
        up = wait_for_ssh(log)
        if up and cfg.open_terminal:
            open_ssh_terminal(log)
        url = start_web(cfg, log)
        if cfg.open_browser:
            open_browser(url, log)
        log("Ready. Hunt in the terminal, submit in the browser. Happy hunting!")
    except Exception as exc:
        log(f"ERROR: {type(exc).__name__}: {exc}")
